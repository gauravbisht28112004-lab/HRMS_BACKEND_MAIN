package com.financebuddha.finbud.hrms.enums;

/**
 * Visual priority of an admin-published announcement. Drives the badge
 * colour on the dashboard ({@code HIGH}=red, {@code MEDIUM}=amber,
 * {@code LOW}=blue) — no business behaviour change between values.
 */
public enum AnnouncementPriority {
    HIGH,
    MEDIUM,
    LOW
}
